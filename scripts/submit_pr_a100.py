def main():
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('--campaign',default='pr-qwen35-a100-10n-v1-20261125')
    p.add_argument('--bundle',default='/mnt/tianzhu/data-picking-v2/runs/pr-a100-bundle-v1-20261125')
    p.add_argument('--nodes',type=int,default=10)
    p.add_argument('--output',default='/tmp/pr-a100-submission')
    p.add_argument('--smoke',action='store_true',help='先只用一个节点验证环境和数值')
    p.add_argument('--submit',action='store_true',help='在当前已配置 amlt 的项目目录实际提交')
    p.add_argument('--windows-wrapper',help='生成内嵌提交程序的 Windows PowerShell 脚本')
    args=p.parse_args()
    if args.nodes!=10:p.error('This immutable bundle uses ten nodes; another partition requires a new deployment')
    import re
    if not re.fullmatch(r'[A-Za-z0-9_-]+',args.campaign):p.error('Invalid campaign name')
    if not re.fullmatch(r'/[A-Za-z0-9_./-]+',args.bundle):p.error('Invalid bundle path')
    output=Path(args.output);(output/'submission').mkdir(parents=True,exist_ok=True)
    (output/'submission/README.txt').write_text('Runtime and code are loaded from the immutable scoring bundle.\n')
    filename=output/('smoke.yaml' if args.smoke else 'score.yaml')
    filename.write_text(json.dumps(configuration(args.campaign,args.bundle,args.nodes,args.smoke),indent=2)+'\n')
    if args.windows_wrapper:windows_wrapper(args.windows_wrapper)
    print(filename)
    experiment=args.campaign+('-smoke' if args.smoke else '')
    command=['amlt','run',str(filename),experiment,'-y']
    print(' '.join(command))
    if args.submit:subprocess.run(command,check=True)


if __name__=='__main__':main()
